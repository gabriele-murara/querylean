"""Location of the files shipped next to the application code."""

from __future__ import annotations

import sys
from pathlib import Path


class BundleResources:
    """Paths of the resources bundled by PyInstaller.

    When frozen, the resources are in the bundle directory
    (``sys._MEIPASS``); when running from sources, in the project root.
    """

    LICENSES_DIR = "licenses"
    THIRD_PARTY_LICENSES = "THIRD_PARTY_LICENSES.txt"
    # src/querylean/app/bundle_resources.py -> project root.
    __SOURCE_ROOT_DEPTH = 3

    @staticmethod
    def is_frozen() -> bool:
        """True inside a PyInstaller bundle."""
        return getattr(sys, "_MEIPASS", None) is not None

    @staticmethod
    def root() -> Path:
        """Bundle directory when frozen, project root from sources."""
        bundle_dir = getattr(sys, "_MEIPASS", None)
        if bundle_dir:
            return Path(bundle_dir)
        depth = BundleResources.__SOURCE_ROOT_DEPTH
        return Path(__file__).resolve().parents[depth]

    @staticmethod
    def third_party_licenses() -> Path:
        """Notices of the bundled third-party components (generated by the
        build: absent when running from sources)."""
        folder = BundleResources.root() / BundleResources.LICENSES_DIR
        return folder / BundleResources.THIRD_PARTY_LICENSES
