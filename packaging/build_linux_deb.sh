#!/usr/bin/env bash
# Builds dist/querylean-<version>-<arch>.deb for Ubuntu/Lubuntu 24.04.
# Run it on Ubuntu 24.04: the bundle needs the glibc of the build system
# (2.38 or later).
# Requirements: Python with the build dependencies (`pip install -e .[build]`)
# and dpkg-deb (dpkg package).
#
# Package contents:
#   /opt/querylean/                      PyInstaller bundle (onedir)
#   /usr/bin/querylean                   launcher
#   /usr/share/applications/             menu entry (.desktop)
#   /usr/share/icons/hicolor/scalable/   icon
#   /usr/share/doc/querylean/copyright   licenses (DEP-5)
#   /usr/share/doc/querylean/THIRD_PARTY_LICENSES.txt   third-party licenses
set -euo pipefail

. "$(dirname "$0")/common.sh"

MAINTAINER="Gabriele Murara <gabriele@murara.computer>"
DEB_ARCH="$(dpkg --print-architecture)"
# Debian version: "X.Y.Z-dev" becomes "X.Y.Z~dev-1" ("~" sorts before the
# final release; "-1" is the package revision).
DEB_VERSION="${VERSION/-/\~}-1"

querylean_pyinstaller

PKG="build/deb/querylean"
rm -rf "build/deb"
mkdir -p "$PKG/DEBIAN" "$PKG/opt" "$PKG/usr/bin" \
         "$PKG/usr/share/applications" \
         "$PKG/usr/share/icons/hicolor/scalable/apps" \
         "$PKG/usr/share/doc/querylean"

cp -a dist/querylean "$PKG/opt/querylean"
install -m 0755 /dev/stdin "$PKG/usr/bin/querylean" <<'EOF'
#!/bin/sh
exec /opt/querylean/querylean "$@"
EOF
install -m 0644 packaging/querylean.desktop "$PKG/usr/share/applications/"
install -m 0644 packaging/querylean.svg \
    "$PKG/usr/share/icons/hicolor/scalable/apps/"
# The bundle contains third-party components, each under its own license:
# their notices (generated by the spec) are linked from the doc directory.
NOTICES="opt/querylean/_internal/licenses/THIRD_PARTY_LICENSES.txt"
if [ ! -s "$PKG/$NOTICES" ]; then
    echo "Third-party licenses missing from the bundle: $NOTICES" >&2
    exit 1
fi
ln -s "/$NOTICES" "$PKG/usr/share/doc/querylean/THIRD_PARTY_LICENSES.txt"
COPYRIGHT_FORMAT="https://www.debian.org/doc/packaging-manuals"
COPYRIGHT_FORMAT+="/copyright-format/1.0/"
{
    echo "Format: ${COPYRIGHT_FORMAT}"
    echo "Upstream-Name: QueryLean"
    echo
    echo "Files: *"
    echo "Copyright: $(sed -n 's/^Copyright (c) //p' LICENSE)"
    echo "License: MIT"
    sed 's/^$/./; s/^/ /' LICENSE
    echo
    echo "Files: opt/querylean/*"
    echo "Copyright: see /usr/share/doc/querylean/THIRD_PARTY_LICENSES.txt"
    echo "License: other"
    echo " The PyInstaller bundle in /opt/querylean contains QueryLean (MIT)"
    echo " and third-party components, each distributed under its own"
    echo " license: Qt and PySide6 (LGPL-3.0), mysql-connector-python (GPLv2"
    echo " with the Universal FOSS Exception, source code included), Python"
    echo " (PSF-2.0), ICU, OpenSSL and other Ubuntu libraries, and several"
    echo " MIT, BSD and Apache-2.0 Python packages. The list, the full license"
    echo " texts and where to obtain the source code are in"
    echo " /usr/share/doc/querylean/THIRD_PARTY_LICENSES.txt."
} > "$PKG/usr/share/doc/querylean/copyright"

# Standard permissions: directories 755, files 644, executables 755.
find "$PKG" -type d -exec chmod 0755 {} +
find "$PKG" -type f ! -perm -u+x -exec chmod 0644 {} +
find "$PKG" -type f -perm -u+x -exec chmod 0755 {} +

INSTALLED_SIZE="$(du -sk --exclude=DEBIAN "$PKG" | cut -f1)"
# Qt, Python and the other libraries are bundled; only the C library and the
# graphics stack come from the system.
cat > "$PKG/DEBIAN/control" <<EOF
Package: querylean
Version: ${DEB_VERSION}
Section: database
Priority: optional
Architecture: ${DEB_ARCH}
Maintainer: ${MAINTAINER}
Installed-Size: ${INSTALLED_SIZE}
Depends: libc6 (>= 2.38), libegl1, libgl1, libxcb1
Recommends: gnome-keyring | keepassxc, libwayland-client0,
 libwayland-cursor0, libwayland-egl1
Description: minimal MySQL client for read-only queries
 QueryLean runs read statements only (SELECT, SHOW, DESCRIBE, EXPLAIN)
 on MySQL, with saved connections (one open at a time), an SQL editor, a
 results table and passwords kept in the system keyring.
EOF
chmod 0644 "$PKG/DEBIAN/control"

OUTPUT="dist/querylean-${VERSION}-${DEB_ARCH}.deb"
rm -f "$OUTPUT"
dpkg-deb --build --root-owner-group -Zxz "$PKG" "$OUTPUT"
echo "Created $OUTPUT"
